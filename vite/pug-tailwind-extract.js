/**
 * pug-tailwind-extract — Vite plugin
 *
 * Why this exists
 * ===============
 * Tailwind v4's content extractor splits candidate tokens on a fixed set
 * of non-class characters. For `.n` files (Pug + Civet), a chain like
 *
 *   .grid.gap-6(class="md:grid-cols-2")
 *
 * looks fine to humans — `grid` and `gap-6` are Pug-shorthand class names.
 * But the extractor reads the substring `.gap-6(` as one non-class token
 * (because `(` isn't in the candidate alphabet) and `gap-6` never reaches
 * the candidate set. The CSS rule never gets generated.
 *
 * The pattern is so idiomatic in `.n` files — shorthand classes followed
 * directly by a `(attrs)` block — that asking authors to either put every
 * utility class inside `class="…"` or manually safelist them in CSS is a
 * paper cut on every page they touch.
 *
 * What this does
 * ==============
 * On `buildStart` and on every `.n` file change, scan the file tree for
 * Pug-shorthand class chains. Extract each chain into its individual
 * classes and write them all into a single sidecar HTML file at
 *
 *   <root>/<outFile>   (default: src/.tailwind-pug-classes.html)
 *
 * which Tailwind picks up via `@source "./.tailwind-pug-classes.html";`
 * in app.css. The file is a single `<div class="…">` with one space-
 * separated copy of every class candidate — Tailwind's own filtering will
 * drop anything that isn't a real utility, so false positives are free.
 *
 * Add the output file to `.gitignore` — it's auto-generated.
 */

import fs from 'node:fs/promises';
import path from 'node:path';

/** Walk a directory recursively and return absolute paths of files matching `ext`. */
async function walk(dir, ext, out = []) {
	let entries;
	try {
		entries = await fs.readdir(dir, { withFileTypes: true });
	} catch {
		return out;
	}
	for (const entry of entries) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
			await walk(full, ext, out);
		} else if (entry.isFile() && full.endsWith(ext)) {
			out.push(full);
		}
	}
	return out;
}

/**
 * Match every `.candidate` segment in the file. Pug shorthand chains
 * (`tag.cls.cls`, `.cls.cls`, etc.) are picked up segment-by-segment.
 *
 * Class names may contain Tailwind's full alphabet — letters, digits, `-`,
 * `_`, `:`, `/`, and arbitrary-value brackets `[...]`. Pug shorthand never
 * contains a `.` inside a class name (the dot is the delimiter), so we
 * don't have to deal with `text-[1.5rem]`-style brackets inside shorthand;
 * those always live inside `class="…"`, which Tailwind extracts directly.
 *
 * Why not anchor the regex (e.g., require preceding whitespace or `(`)?
 * Pug shorthand can follow a TAG NAME with no separator (`th.text-left`),
 * follow other shorthand (`.a.b`), or sit at line start. Anchoring to any
 * single boundary mode misses one of the cases. We accept false positives
 * here — strings like `.svelte` inside template text get captured too —
 * because Tailwind filters them out anyway: only candidates that match a
 * real utility class generate CSS. The cost is a few extra bytes in the
 * sidecar; the gain is "every legitimate shorthand class just works."
 */
const SEGMENT_RE = /\.([A-Za-z][\w\-:/]*(?:\[[^\]]*\])?)/g;

function extractClasses(source) {
	const out = new Set();
	let m;
	SEGMENT_RE.lastIndex = 0;
	while ((m = SEGMENT_RE.exec(source))) {
		if (m[1]) out.add(m[1]);
	}
	return out;
}

/**
 * @param {object} [options]
 * @param {string} [options.root]       Directory to scan. Default `src`.
 * @param {string} [options.ext]        File extension. Default `.n`.
 * @param {string} [options.outFile]    Sidecar file relative to root. Default `.tailwind-pug-classes.html`.
 * @returns {import('vite').Plugin}
 */
export function pugTailwindExtract({
	root = 'src',
	ext = '.n',
	outFile = '.tailwind-pug-classes.html'
} = {}) {
	let projectRoot = process.cwd();
	const fileClasses = new Map(); // absolute path -> Set<string>

	async function writeSidecar() {
		const all = new Set();
		for (const set of fileClasses.values()) {
			for (const c of set) all.add(c);
		}
		const sorted = [...all].sort();
		const html =
			'<!-- AUTO-GENERATED by pug-tailwind-extract. Do not edit. -->\n' +
			`<div class="${sorted.join(' ')}"></div>\n`;
		const out = path.join(projectRoot, root, outFile);
		await fs.mkdir(path.dirname(out), { recursive: true });
		await fs.writeFile(out, html, 'utf8');
	}

	async function scanFile(abs) {
		try {
			const content = await fs.readFile(abs, 'utf8');
			fileClasses.set(abs, extractClasses(content));
		} catch {
			fileClasses.delete(abs);
		}
	}

	async function scanAll() {
		const dir = path.join(projectRoot, root);
		const files = await walk(dir, ext);
		await Promise.all(files.map(scanFile));
		await writeSidecar();
	}

	return {
		name: 'pug-tailwind-extract',
		// Run before plugins that transform .n files; we want raw Pug.
		enforce: 'pre',
		configResolved(config) {
			projectRoot = config.root || process.cwd();
		},
		async buildStart() {
			await scanAll();
		},
		async handleHotUpdate({ file }) {
			if (!file.endsWith(ext)) return;
			await scanFile(file);
			await writeSidecar();
		},
		configureServer(server) {
			// Pick up newly-created `.n` files in dev.
			server.watcher.on('add', async (file) => {
				if (!file.endsWith(ext)) return;
				await scanFile(file);
				await writeSidecar();
			});
			server.watcher.on('unlink', async (file) => {
				if (!file.endsWith(ext)) return;
				fileClasses.delete(file);
				await writeSidecar();
			});
		}
	};
}
